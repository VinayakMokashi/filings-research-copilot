"""Write a sheet of 20 random annual values to check by hand against the filings.

The values are drawn with a fixed seed from fiscal years 2015 to 2023, and each row links to
the 10-K it came from on EDGAR. Writes docs/data/facts-spot-check.md.

Usage: uv run poe spot-check-facts   (after `poe build-facts`)
"""

from __future__ import annotations

import random
from pathlib import Path

from copilot.config import get_settings
from copilot.facts.database import connect_read_only

SEED = 2026
SAMPLE_SIZE = 20
OUT = Path("docs/data/facts-spot-check.md")
FILING_INDEX = "https://www.sec.gov/Archives/edgar/data/{cik}/{folder}/{accn}-index.htm"


def _format(value: float, unit: str) -> str:
    if unit == "USD/shares":
        return f"${value:,.2f}"
    if unit == "shares":
        return f"{value / 1e6:,.1f} million shares"
    return f"${value / 1e6:,.1f} million"


def main() -> int:
    conn = connect_read_only(get_settings().data_dir / "processed" / "facts.db")
    try:
        rows = conn.execute(
            "SELECT c.name, a.cik, m.label, a.fiscal_year, a.value, a.unit, a.period_end, "
            "a.accn, a.tag FROM annual_values AS a JOIN companies AS c USING (cik) "
            "JOIN metrics AS m USING (metric) WHERE a.fiscal_year BETWEEN 2015 AND 2023 "
            "ORDER BY a.cik, a.metric, a.fiscal_year"
        ).fetchall()
    finally:
        conn.close()
    sample = sorted(random.Random(SEED).sample(rows, SAMPLE_SIZE), key=lambda r: (r[0], r[3], r[2]))

    lines = [
        "# Spot check: 20 facts against the filings",
        "",
        f"Twenty annual values drawn at random (seed {SEED}) from the facts database, fiscal "
        "years 2015 to 2023, generated by `uv run poe spot-check-facts`. To check one, open its "
        "filing, find the statement the metric comes from (income statement, cash flow statement "
        "or balance sheet), and compare the figure for the fiscal year shown. Companies usually "
        "report in millions or thousands, so expect rounding in the last digit. Record the "
        "outcome in the last column.",
        "",
        "| # | Company | Metric | Fiscal year | Value | Period end | XBRL tag | Filing "
        "| Matches the filing? |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for number, (name, cik, label, year, value, unit, period_end, accn, tag) in enumerate(
        sample, start=1
    ):
        link = FILING_INDEX.format(cik=cik, folder=accn.replace("-", ""), accn=accn)
        lines.append(
            f"| {number} | {name} | {label} | {year} | {_format(value, unit)} | {period_end} | "
            f"`{tag}` | [10-K]({link}) | |"
        )
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"Wrote {OUT} with {SAMPLE_SIZE} values")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
